"""The bench database: the same schema as the app database, holding only bench data.

Why a separate database: a 100k-user bench run must never mix generated users or synthetic
products into the `loans` database that n8n and Workflow A use. ``loans_bench`` lives on the
same local app-db server, is migrated with the same files, and can be rebuilt at any time
(it holds nothing that isn't regenerated by the bench).

Products come from one of two sets:
    real       the active products Workflow A crawled, copied from the `loans` database
    synthetic  bench/fixtures/synthetic_products.json, which covers every criterion class
"""

import hashlib
import json
import uuid
from pathlib import Path
from typing import Any, Literal

import psycopg
from psycopg import sql
from psycopg.types.json import Jsonb

from scripts import migrate, seed_config
from scripts.dbconn import admin_connect_kwargs
from scripts.envfile import REPO_ROOT, load_settings

BENCH_DB = "loans_bench"
SYNTHETIC = REPO_ROOT / "bench" / "fixtures" / "synthetic_products.json"
ProductSet = Literal["real", "synthetic"]

PRODUCT_COLUMNS = (
    "lender", "product_name", "source_url", "interest_rate_min", "interest_rate_max",
    "min_monthly_income", "min_credit_score", "min_age", "max_age", "allowed_employment",
    "soft_criteria", "field_confidence", "criteria_json", "criteria_hash", "content_hash",
)  # fmt: skip


def connect(database: str = BENCH_DB, autocommit: bool = True) -> psycopg.Connection:
    """Open an admin connection to the bench (or another local) database."""
    return psycopg.connect(
        **admin_connect_kwargs(load_settings(), "local", database), autocommit=autocommit
    )


def recreate(products: ProductSet) -> None:
    """Drop and rebuild the bench database, then load one product set."""
    settings = load_settings()
    with connect(settings.get("APP_DB_NAME", "loans")) as admin:
        admin.execute(
            sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(BENCH_DB))
        )
        admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(BENCH_DB)))
    migrate.run("local", BENCH_DB)
    seed_config.store("local", seed_config.build_config(settings), BENCH_DB)
    with connect() as conn:
        if products == "real":
            copy_real_products(conn, settings.get("APP_DB_NAME", "loans"))
        else:
            load_synthetic_products(conn)


def copy_real_products(conn: psycopg.Connection, source_db: str) -> int:
    """Copy the crawled sources and active products from the app database."""
    with connect(source_db) as src:
        sources = src.execute(
            "SELECT slug, display_name, kind, page_urls, fixture_files FROM crawl_sources"
        ).fetchall()
        rows = src.execute(
            f"SELECT s.slug, {', '.join('p.' + c for c in PRODUCT_COLUMNS)} "
            "FROM loan_products p JOIN crawl_sources s USING (source_id) WHERE p.is_active"
        ).fetchall()
    ids = {}
    for slug, name, kind, urls, fixtures in sources:
        row = conn.execute(
            "INSERT INTO crawl_sources (slug, display_name, kind, page_urls, fixture_files) "
            "VALUES (%s, %s, %s, %s, %s) RETURNING source_id",
            (slug, name, kind, urls, fixtures),
        ).fetchone()
        assert row is not None
        ids[slug] = row[0]
    insert_products(conn, [(ids[r[0]], *r[1:]) for r in rows])
    return len(rows)


def criteria_hash(criteria: dict[str, Any]) -> str:
    """Stable hash of the decision-relevant criteria (bench products only)."""
    return hashlib.sha256(
        json.dumps(criteria, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


def load_synthetic_products(conn: psycopg.Connection, path: Path = SYNTHETIC) -> int:
    """Load the synthetic product set under one disabled bench source."""
    row = conn.execute(
        "INSERT INTO crawl_sources (slug, display_name, kind, page_urls, enabled) "
        "VALUES ('synthetic-bench', 'Synthetic bench products', 'lender', "
        "ARRAY['https://bench.invalid/products'], false) RETURNING source_id"
    ).fetchone()
    assert row is not None
    rows = []
    for p in json.loads(path.read_text(encoding="utf-8"))["products"]:
        criteria = {
            k: p[k]
            for k in ("interest_rate_min", "interest_rate_max", "min_monthly_income",
                      "min_credit_score", "min_age", "max_age", "allowed_employment",
                      "soft_criteria")
        }  # fmt: skip
        digest = criteria_hash(criteria)
        rows.append((
            row[0], p["lender"], p["product_name"], "https://bench.invalid/products",
            p["interest_rate_min"], p["interest_rate_max"], p["min_monthly_income"],
            p["min_credit_score"], p["min_age"], p["max_age"], p["allowed_employment"],
            Jsonb(p["soft_criteria"]), Jsonb({}), Jsonb(criteria), digest, "bench",
        ))  # fmt: skip
    insert_products(conn, rows)
    return len(rows)


def insert_products(conn: psycopg.Connection, rows: list[tuple[Any, ...]]) -> None:
    """Insert product rows given as (source_id, *PRODUCT_COLUMNS)."""
    columns = ", ".join(("source_id", *PRODUCT_COLUMNS))
    placeholders = ", ".join(["%s"] * (len(PRODUCT_COLUMNS) + 1))
    adapted = [
        tuple(Jsonb(v) if isinstance(v, (dict, list)) and i in (11, 12, 13) else v
              for i, v in enumerate(r))
        for r in rows
    ]  # fmt: skip
    with conn.cursor() as cur:
        cur.executemany(
            f"INSERT INTO loan_products ({columns}) VALUES ({placeholders})",
            adapted,
        )


def clear_batches(conn: psycopg.Connection) -> None:
    """Remove every batch and what hangs off it, so a run starts from an empty pipeline."""
    conn.execute(
        "TRUNCATE user_matches, notifications, pipeline_metrics, users, ingestion_batches, "
        "llm_decisions, criterion_rules RESTART IDENTITY"
    )


def load_batch(conn: psycopg.Connection, users: list[dict[str, str]], label: str) -> str:
    """Insert one 'ingested' batch and its users, the state Workflow B starts from.

    A user who already exists (a re-upload) moves to the new batch with the new facts, as the
    ingest Lambda will do: the last upload of a user wins. User ids within one call must be
    unique.
    """
    batch_id = str(uuid.uuid4())
    conn.execute(
        "INSERT INTO ingestion_batches (batch_id, s3_bucket, s3_key, etag, status, rows_total, "
        "rows_valid, rows_rejected, ingested_at) "
        "VALUES (%s, 'bench', %s, %s, 'ingested', %s, %s, 0, now())",
        (batch_id, f"bench/{label}.csv", f"bench-{batch_id}", len(users), len(users)),
    )
    columns = "user_id, name, email, monthly_income, credit_score, employment_status, age, batch_id"
    conn.execute(
        f"CREATE TEMP TABLE IF NOT EXISTS users_stage AS SELECT {columns} FROM users LIMIT 0"
    )
    conn.execute("TRUNCATE users_stage")
    with conn.cursor() as cur, cur.copy(f"COPY users_stage ({columns}) FROM STDIN") as copy:
        for u in users:
            copy.write_row((u["user_id"], u["name"], u["email"], u["monthly_income"],
                            u["credit_score"], u["employment_status"], u["age"],
                            batch_id))  # fmt: skip
    conn.execute(
        f"INSERT INTO users ({columns}) SELECT {columns} FROM users_stage "
        "ON CONFLICT (user_id) DO UPDATE SET name = EXCLUDED.name, email = EXCLUDED.email, "
        "monthly_income = EXCLUDED.monthly_income, credit_score = EXCLUDED.credit_score, "
        "employment_status = EXCLUDED.employment_status, age = EXCLUDED.age, "
        "batch_id = EXCLUDED.batch_id, updated_at = now()"
    )
    conn.execute("ANALYZE users")
    return batch_id
